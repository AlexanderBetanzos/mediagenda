<h2 id="roles">Quién usa qué</h2>
<ul>
    <li><b>Administrador</b>: todo, incluida la configuración, el personal, la bitácora y la suscripción.</li>
    <li><b>Médico</b>: su agenda, expedientes, consultas, recetas y su firma electrónica.</li>
    <li><b>Recepción</b>: agenda, pacientes, cobros y caja.</li>
</ul>
