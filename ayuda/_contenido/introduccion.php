<h2 id="que-es">Qué es MediAgenda</h2>
<p>MediAgenda es el sistema en la nube para consultorios y clínicas: agenda, expediente clínico, recetas, cobros, facturación y comunicación con tus pacientes en un solo lugar. Funciona desde el navegador de tu computadora, tablet o celular; no hay nada que instalar.</p>

